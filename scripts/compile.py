# ② DDL (PostgreSQL)
# ──────────────────────────────────────────────────────────────
def compile_ddl(sc: dict) -> str:
    upper = sc["upper"]
    domain = sc.get("domain", {})
    app = sc.get("application", {})
    lines: list[str] = [
        f"-- Generated by Sloth-OntoForge-Den v2 on {dt.date.today()}",
        f"-- Scenario: {sc['meta']['name_cn']}",
        "",
        "CREATE EXTENSION IF NOT EXISTS \"uuid-ossp\";",
        "",
    ]

    # --- Kinds → 表 ---
    for k in upper.get("kinds", []) + domain.get("kinds", []):
        tbl = to_table(k["id"])
        pi = k.get("pi", "id")
        pi_cols = []
        for p in pi.replace(" ", "").split("+"):
            pi_cols.append(f"    {p.strip()} VARCHAR({PI_VARCHAR_WIDTH}) UNIQUE NOT NULL")
        lines.append(f"-- <<kind>> {k['label']} (PI: {pi})")
        lines.append(f"CREATE TABLE {tbl} (")
        lines.append("    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),")
        lines.extend([c + "," for c in pi_cols])
        lines.append("    created_at TIMESTAMPTZ DEFAULT NOW(),")
        lines.append("    updated_at TIMESTAMPTZ DEFAULT NOW()")
        lines.append(");")
        lines.append("")

    # --- Modes → 内联列（依附 Kind，不建独立表） ---
    for m in domain.get("modes", []):
        of_list = m["of"] if isinstance(m["of"], list) else [m["of"]]
        of_tbl = to_table(of_list[0])
        col = snake(m["id"])
        if "enum" in m:
            enum_vals = ", ".join(f"'{v}'" for v in m["enum"])
            lines.append(f"ALTER TABLE {of_tbl} ADD COLUMN {col} VARCHAR(32) CHECK ({col} IN ({enum_vals}));")
        else:
            sql_type = XSD_TO_PG.get(m["xsd"], "TEXT")
            lines.append(f"ALTER TABLE {of_tbl} ADD COLUMN {col} {sql_type};")
    lines.append("")

    # --- Relators → 关联表 ---
    for rel in upper.get("relators", []):
        tbl = to_table(rel["id"])
        lines.append(f"-- <<relator>> {rel['label']}")
        lines.append(f"CREATE TABLE {tbl} (")
        lines.append("    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),")
        for b in rel["binds"]:
            b_tbl = to_table(b)
            lines.append(f"    {b_tbl}_id UUID NOT NULL REFERENCES {b_tbl}(id),")
        lines.append("    created_at TIMESTAMPTZ DEFAULT NOW()")
        lines.append(");")
        lines.append("")

    # --- Phases → 状态字段 (追加到主表) ---
    for ph in app.get("phases", []):
        tbl = to_table(ph["of"])
        states = ", ".join(f"'{s}'" for s in ph["states"])
        lines.append(f"-- <<phase>> of {tbl}")
        lines.append(f"ALTER TABLE {tbl} ADD COLUMN {PHASE_COLUMN} VARCHAR(32)")
        lines.append(f"    DEFAULT '{ph['initial']}'")
        lines.append(f"    CHECK ({PHASE_COLUMN} IN ({states}));")
        lines.append("")

    # --- Qualities → 列 (追加到对应表) ---
    for q in domain.get("qualities", []):
        of_list = q["of"] if isinstance(q["of"], list) else [q["of"]]
        sql_type = XSD_TO_PG.get(q["xsd"], "TEXT")
        col = snake(q["id"])
        for o in of_list:
            target = to_table(o)
            lines.append(f"ALTER TABLE {target} ADD COLUMN {col} {sql_type};")
    lines.append("")

    # --- 状态转移约束触发器 ---
    lines.append("-- ===================== STATE MACHINE TRIGGERS =====================")
    for ph in app.get("phases", []):
        tbl = to_table(ph["of"])
        fn = f"tr_{tbl}_phase_guard"
        allowed: list[str] = []
        for t in ph.get("transitions", []):
            allowed.append(f"  IF OLD.{PHASE_COLUMN} = '{t['from']}' AND NEW.{PHASE_COLUMN} = '{t['to']}' THEN RETURN NEW; END IF;")
        body = "\n".join(allowed) if allowed else "  RETURN NEW;"
        lines.append(f"CREATE OR REPLACE FUNCTION {fn}() RETURNS TRIGGER AS $$")
        lines.append("BEGIN")
        lines.append(f"  IF OLD.{PHASE_COLUMN} = NEW.{PHASE_COLUMN} THEN RETURN NEW; END IF;")
        lines.append(body)
        lines.append(f"  RAISE EXCEPTION '非法状态转移: % → %', OLD.{PHASE_COLUMN}, NEW.{PHASE_COLUMN};")
        lines.append("END;")
        lines.append(f"$$ LANGUAGE plpgsql;")
        lines.append("")
        lines.append(f"CREATE TRIGGER {fn}")
        lines.append(f"  BEFORE UPDATE ON {tbl}")
        lines.append(f"  FOR EACH ROW EXECUTE FUNCTION {fn}();")
        lines.append("")

    return "\n".join(lines)



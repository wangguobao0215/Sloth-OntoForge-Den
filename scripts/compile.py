import json


def compile_commands(sc: dict) -> str:
    app = sc.get("application", {})
    out = {
        "scenario": sc["meta"]["id"],
        "generated_at": dt.datetime.now().isoformat(timespec="seconds"),
        "commands": app.get("commands", []),
        "queries": app.get("queries", []),
        "events": [
            {"id": e["id"], "label": e["label"], "triggers": e["triggers"]}
            for e in app.get("events", [])
        ],
    }
    return json.dumps(out, ensure_ascii=False, indent=2)


# ──────────────────────────────────────────────────────────────
# ⑤ LLM Prompt (verbalization)
# ──────────────────────────────────────────────────────────────
def compile_prompt(sc: dict) -> str:
    v = sc.get("verbalization", {})
    upper = sc["upper"]
    domain = sc.get("domain", {})
    app = sc.get("application", {})

    # ── 核心业务对象（去本体论术语） ──
    all_kinds = upper.get("kinds", []) + domain.get("kinds", [])
    kinds = [f"- {k['label']}（`{k['id']}`）：用 **{k.get('pi', '—')}** 唯一识别"
             for k in all_kinds]

    # ── ID → 业务标签查找表 ──
    all_roles = upper.get("roles", [])
    all_relators = upper.get("relators", []) + domain.get("relators", [])
    id_to_label: dict[str, str] = {}
    for item in all_kinds + all_roles + all_relators:
        id_to_label[item["id"]] = item["label"]

    def resolve_ids(ids: list[str]) -> str:
        """将 ONT_ ID 列表解析为业务标签字符串。"""
        return "、".join(id_to_label.get(i, i) for i in ids)

    # ── 业务角色 ──
    roles = [f"- **{r['label']}**：在{resolve_ids(r['depends_on'])}中承担职责的一方"
             for r in all_roles]

    # ── 业务关系 ──
    relators = [f"- **{rel['label']}**：将{resolve_ids(rel['binds'])}绑定在一起的业务纽带"
                for rel in all_relators]

    # ── event_id → event_label 查找表 ──
    event_labels: dict[str, str] = {}
    for e in app.get("events", []):
        event_labels[e["id"]] = e.get("label", e["id"])

    # ── 状态流转规则（从 transitions 图生成，展示分支） ──
    phases_block = []
    for ph in app.get("phases", []):
        target_id = ph["of"]
        target_label = id_to_label.get(target_id, target_id)
        initial = ph.get("initial", ph["states"][0] if ph["states"] else "?")
        transitions = ph.get("transitions", [])

        if not transitions:
            # 无 transitions 定义时退化为线性列表
            states_str = " → ".join(ph["states"])
            phases_block.append(f"- **{target_label}**状态流转：{states_str}（只能按顺序推进，禁止跳跃）")
            continue

        # 按 from 状态分组 transitions
        from_groups: dict[str, list[dict]] = {}
        for t in transitions:
            from_groups.setdefault(t["from"], []).append(t)

        phases_block.append(f"- **{target_label}**状态流转规则（初始: {initial}）：")
        for from_state, group in from_groups.items():
            targets = []
            for t in group:
                evt_label = event_labels.get(t["event"], t["event"])
                guard = t.get("guard", "")
                desc = f"{t['to']}（{evt_label}）" + (f"，条件: {guard}" if guard else "")
                targets.append(desc)
            phases_block.append(f"  - {from_state} → {' 或 '.join(targets)}")

    # ── 命令路由表 ──
    commands_block = "\n".join(
        f"- `{c['name']}` → {c['endpoint']}" + (f"（需要 **{c['role']}** 角色）" if 'role' in c else "")
        for c in app.get("commands", [])
    )

    # ── Few-shot 路由示例（从 YAML verbalization.examples 提取） ──
    examples = v.get("examples", [])
    few_shot_lines = []
    for ex in examples:
        few_shot_lines.append(f"- 用户说：「{ex['natural']}」 → 路由：{ex['route']}")

    # ── 自动生成业务规则（替代 {<<kind>>} 模板变量） ──
    auto_axioms = []
    # 规则1: 核心对象识别
    kind_names = "、".join(k["label"] for k in all_kinds[:6])
    if len(all_kinds) > 6:
        kind_names += f"等 {len(all_kinds)} 类"
    auto_axioms.append(f"核心业务对象包括{kind_names}，每个对象都有唯一识别码")
    # 规则2: 角色不是职位
    if upper.get("roles"):
        role_names = "、".join(r["label"] for r in upper["roles"][:4])
        auto_axioms.append(f"{role_names}是业务关系中承担职责的角色，不是员工的行政职位")
    # 规则3: 状态机约束
    if app.get("phases"):
        phase_targets = "、".join(
            next((k["label"] for k in all_kinds if k["id"] == ph["of"]), ph["of"])
            for ph in app["phases"]
        )
        auto_axioms.append(f"{phase_targets}都有严格的状态流转规则，状态只能按顺序推进，禁止跳跃或回退")

    # ── 合并用户自定义公理（跳过模板变量类的条目） ──
    user_axioms = [a for a in v.get("axioms", []) if "{<<" not in a]
    all_axioms = auto_axioms + user_axioms

    # ── 路由规则（去本体论化） ──
    routing_rules = [
        "用户请求涉及**创建、修改、审批、提交**等写操作 → 路由到对应的 /命令，禁止 LLM 自行生成",
        "用户请求涉及**查询、统计、分析**等读操作 → 用知识图谱上下文回答",
        "用户请求超出本场景范围 → 明确告知「这不在我的服务范围内」并拒绝",
    ]

    prompt = f"""# System Prompt — {v.get('domain_name', sc['meta']['name_cn'])}

你是 {v.get('domain_name', sc['meta']['name_cn'])} 领域的 AI 助理。
你的职责是帮助用户完成业务流程操作和回答业务相关问题。

## 核心业务对象
{chr(10).join(kinds)}

## 业务角色
{chr(10).join(roles)}

## 业务关系
{chr(10).join(relators)}

## 状态流转规则
{chr(10).join(phases_block)}

## 业务规则
{chr(10).join('- ' + a for a in all_axioms)}

## 路由规则
{chr(10).join('- ' + r for r in routing_rules)}

## 可用命令（写操作必须路由到 API，禁止 LLM 代写）
{commands_block}
{chr(10).join(few_shot_lines) if few_shot_lines else ""}

## 边界
以下概念**不在本场景范围内**，若用户提及必须明确拒绝：
{chr(10).join('- ' + x for x in sc['meta'].get('realism_statement', {}).get('nonexistent', []))}
"""
    return prompt


# ──────────────────────────────────────────────────────────────
# ⑥ RBAC (FastAPI 权限依赖)
# ──────────────────────────────────────────────────────────────
def compile_rbac(sc: dict) -> str:
    """生成 FastAPI RBAC 依赖模块：role → command 可见性 + 服务端校验。"""
    app = sc.get("application", {})
    commands = app.get("commands", [])

    # 构建 role → commands 映射
    role_cmds: dict[str, list[str]] = {}
    for c in commands:
        role = c.get("role", "any")
        role_cmds.setdefault(role, []).append(c["name"])

    # 构建 command → role 映射（用于服务端校验）
    cmd_role: dict[str, str] = {}
    for c in commands:
        cmd_role[c["name"]] = c.get("role", "any")

    lines = [
        f'"""',
        f'RBAC 权限依赖 — {sc["meta"]["name_cn"]}',
        f'',
        f'自动生成，请勿手改。',
        f'Generator: Sloth-OntoForge-Den · 树懒 · 本体锻炉 v2',
        f'',
        f'用法:',
        f'  from rbac import require_role, ROLE_COMMANDS',
        f'',
        f'  @app.post("/api/quotation/{{id}}/approve")',
        f'  async def approve(id: str, user=Depends(require_role("Approver"))):',
        f'      ...',
        f'"""',
        f'',
        f'from __future__ import annotations',
        f'',
        f'from fastapi import Depends, HTTPException, status',
        f'from fastapi.security import HTTPBearer',
        f'',
        f'security = HTTPBearer()',
        f'',
        f'# role → 可执行的 /命令清单',
        f'ROLE_COMMANDS: dict[str, list[str]] = {{',
    ]
    for role, cmds in sorted(role_cmds.items()):
        cmds_str = ", ".join(f'"{c}"' for c in cmds)
        lines.append(f'    "{role}": [{cmds_str}],')
    lines.append(f'}}')
    lines.append('')

    # command → required role
    lines.append('# /命令 → 所需 role')
    lines.append('COMMAND_ROLE: dict[str, str] = {')
    for cmd, role in sorted(cmd_role.items()):
        lines.append(f'    "{cmd}": "{role}",')
    lines.append('}')
    lines.append('')

    # 角色列表
    all_roles = sorted(set(cmd_role.values()))
    roles_str = ", ".join(f'"{r}"' for r in all_roles)
    lines.append(f'ALL_ROLES: list[str] = [{roles_str}]')
    lines.append('')

    # require_role 依赖
    lines.append(f'def require_role(role: str):')
    lines.append(f'    """FastAPI 依赖：校验当前用户拥有指定 role。"""')
    lines.append(f'    async def _check(token=Depends(security)):')
    lines.append(f'        # TODO: 替换为实际的 token 解析 + role 查询')
    lines.append(f'        user_roles = _resolve_roles(token.credentials)')
    lines.append(f'        if role != "any" and role not in user_roles:')
    lines.append(f'            raise HTTPException(')
    lines.append(f'                status_code=status.HTTP_403_FORBIDDEN,')
    lines.append(f'                detail=f"需要角色 {{role}}，当前角色: {{user_roles}}",')
    lines.append(f'            )')
    lines.append(f'        return {{"token": token.credentials, "roles": user_roles}}')
    lines.append(f'    return _check')
    lines.append('')

    # check_command_access
    lines.append(f'def check_command_access(command_name: str, user_roles: list[str]) -> bool:')
    lines.append(f'    """检查用户是否有权执行指定 /命令。"""')
    lines.append(f'    required = COMMAND_ROLE.get(command_name, "any")')
    lines.append(f'    if required == "any":')
    lines.append(f'        return True')
    lines.append(f'    return required in user_roles')
    lines.append('')

    # _resolve_roles stub
    lines.append(f'def _resolve_roles(token: str) -> list[str]:')
    lines.append(f'    """')
    lines.append(f'    解析 JWT token 返回用户角色列表。')
    lines.append(f'    TODO: 替换为实际的 JWT 解码 + 角色查询逻辑。')
    lines.append(f'    """')
    lines.append(f'    # import jwt')
    lines.append(f'    # payload = jwt.decode(token, SECRET_KEY, algorithms=["HS256"])')
    lines.append(f'    # return payload.get("roles", [])')
    lines.append(f'    return ["any"]  # placeholder')
    lines.append('')

    return "\n".join(lines)



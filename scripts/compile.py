# ③ OpenAPI 3.0
# ──────────────────────────────────────────────────────────────
def compile_openapi(sc: dict) -> str:
    meta = sc["meta"]
    app = sc.get("application", {})
    lines: list[str] = [
        "openapi: 3.0.3",
        "info:",
        f"  title: {meta['name_cn']} API",
        f"  version: {meta.get('version', '1.0.0')}",
        f"  description: |",
        f"    {meta.get('scope', '').replace(chr(10), ' ').strip()}",
        "paths:",
    ]

    # 为每个 command 生成 path
    seen_paths: set[str] = set()
    for cmd in app.get("commands", []):
        endpoint = cmd["endpoint"]
        method, path = endpoint.split(" ", 1)
        method = method.lower()
        # 把 {id} 参数声明
        if path not in seen_paths:
            seen_paths.add(path)
            lines.append(f"  {path}:")
        lines.append(f"    {method}:")
        lines.append(f"      operationId: {cmd['name'].lstrip('/').replace('-', '_')}")
        lines.append(f"      summary: {cmd['name']} ({cmd['type']})")
        if "role" in cmd:
            lines.append(f"      security:")
            lines.append(f"        - role: [{cmd['role']}]")
        lines.append(f"      responses:")
        lines.append(f"        '200': {{ description: OK }}")
        lines.append(f"        '400': {{ description: 状态转移不合法 }}")
        lines.append(f"        '403': {{ description: role 不匹配 }}")
    lines.append("")
    return "\n".join(lines)


